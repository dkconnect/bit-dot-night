def get_1d_radial_psd(mag_sq, num_bins=60):
    h, w = mag_sq.shape
    cy, cx = h // 2, w // 2
    ys, xs = np.indices((h, w))
    r = np.sqrt(((xs - cx) / cx)**2 + ((ys - cy) / cy)**2)

    r_flat = r.flatten()
    p_flat = mag_sq.flatten()

    bin_edges = np.linspace(0.02, 0.8, num_bins + 1)
    bin_centers = 0.5 * (bin_edges[:-1] + bin_edges[1:])
    radial_prof = np.zeros(num_bins)

    for i in range(num_bins):
        mask = (r_flat >= bin_edges[i]) & (r_flat < bin_edges[i+1])
        if np.any(mask):
            radial_prof[i] = np.mean(p_flat[mask])
        else:
            radial_prof[i] = 1e-12
    return bin_centers, radial_prof

