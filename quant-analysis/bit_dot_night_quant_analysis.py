def compute_metrics(L: np.ndarray):
    """
    Evaluates Brightness Variance, Structural Coherence, and 2D FFT Radial Energy Partitioning.
    """
    h, w = L.shape

    # 1. Brightness
    var_val = float(np.var(L))

    # 2. Structural Coherence
    diff_h = np.abs(L[:, :-1] - L[:, 1:])
    diff_v = np.abs(L[:-1, :] - L[1:, :])
    min_h, min_w = min(diff_h.shape[0], diff_v.shape[0]), min(diff_h.shape[1], diff_v.shape[1])
    coherence = float(0.5 * (diff_h[:min_h, :min_w].mean() + diff_v[:min_h, :min_w].mean()))

    # 3. 2D Spectral Energy Bands via FFT
    F = fftshift(fft2(L))
    mag_sq = np.abs(F) ** 2
    total_energy = mag_sq.sum()

    cy, cx = h // 2, w // 2
    ys = (np.arange(h) - cy) / cy
    xs = (np.arange(w) - cx) / cx
    XX, YY = np.meshgrid(xs, ys)
    R = np.sqrt(XX**2 + YY**2)

    e_low = float(mag_sq[R <= LOW_BAND_CUTOFF].sum())
    e_mid = float(mag_sq[(R > LOW_BAND_CUTOFF) & (R <= MID_BAND_CUTOFF)].sum())
    e_high = float(mag_sq[R > MID_BAND_CUTOFF].sum())

    low_pct = (e_low / total_energy) * 100.0 if total_energy > 0 else 0.0
    mid_pct = (e_mid / total_energy) * 100.0 if total_energy > 0 else 0.0
    high_pct = (e_high / total_energy) * 100.0 if total_energy > 0 else 0.0

    return var_val, low_pct, mid_pct, high_pct, coherence, mag_sq

