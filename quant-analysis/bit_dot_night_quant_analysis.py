from scipy.stats import linregress

def spatial_shannon_entropy(L: np.ndarray, bins: int = 64) -> float:
    """
    Computes 1st-order Shannon Entropy H(L) = -sum(p * log2(p)).
    Measures information density and tonal uncertainty.
    """
    hist, _ = np.histogram(L, bins=bins, range=(0.0, 1.0), density=True)
    p = hist / np.sum(hist)
    p = p[p > 0]
    return float(-np.sum(p * np.log2(p)))

def spectral_decay_exponent(mag_sq: np.ndarray) -> float:
    """
    Fits Power-law decay: S(f) ~ 1 / f^beta.
    beta ~ 0: White noise (high-frequency random)
    beta ~ 1: 1/f Pink noise (natural structures, architectural facades)
    beta ~ 2: Brownian/Gaussian diffusion (smooth gradients)
    """
    h, w = mag_sq.shape
    cy, cx = h // 2, w // 2
    ys, xs = np.indices((h, w))
    r = np.sqrt(((xs - cx) / cx)**2 + ((ys - cy) / cy)**2)

    mask = (r > 0.02) & (r <= 0.8)
    r_vals = r[mask]
    p_vals = mag_sq[mask]

    log_r = np.log10(r_vals)
    log_p = np.log10(p_vals + 1e-12)

    slope, _, _, _, _ = linregress(log_r, log_p)
    return float(-slope)

def morans_spatial_autocorrelation(L: np.ndarray, subsample_step: int = 8) -> float:
    """
    Computes Moran's I for spatial spatial clustering and autocorrelation.
    I > 0: Clustered/Structured, I = 0: Random, I < 0: Dispersed/Checkerboard.
    """
    sub = L[::subsample_step, ::subsample_step]
    h, w = sub.shape
    z = sub - np.mean(sub)
    s0 = np.sum(z**2)
    if s0 == 0:
        return 0.0

    lag = np.zeros_like(z)
    lag[1:, :] += z[:-1, :]
    lag[:-1, :] += z[1:, :]
    lag[:, 1:] += z[:, :-1]
    lag[:, :-1] += z[:, 1:]

    I = (h * w / (4 * h * w)) * (np.sum(z * lag) / s0)
    return float(I)

