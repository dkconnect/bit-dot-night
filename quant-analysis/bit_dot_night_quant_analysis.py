def generate_luminance_field(op_func, seed_x: int, seed_y: int, seed_scale: int,
                             h: int = GRID_HEIGHT, w: int = GRID_WIDTH) -> np.ndarray:
    """
    Simulates the core Bit Dot Night discrete coordinate mapping and cosine luminance field.
    f(x, y) = O(x + sx, y + sy)
    L(x, y) = 0.5 * (1.0 + cos(f(x, y) * k)) normalized to [0, 1]
    """
    ys, xs = np.indices((h, w), dtype=np.int64)
    X = xs + seed_x
    Y = ys + seed_y

    O = op_func(X, Y)

    L = 0.5 * (1.0 + np.cos(O * (seed_scale * 1e-6)))

    return L.astype(np.float32)

